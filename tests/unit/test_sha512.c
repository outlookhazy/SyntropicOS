void test_sha512_nist_vectors(void)
{
    /* Vector 1: "abc" */
    static const char msg1[] = "abc";
    static const uint8_t exp1[64] = {
        0xdd, 0xaf, 0x35, 0xa1, 0x93, 0x61, 0x7a, 0xba, 0xcc, 0x41, 0x73, 0x49, 0xae,
        0x20, 0x41, 0x31, 0x12, 0xe6, 0xfa, 0x4e, 0x89, 0xa9, 0x7e, 0xa2, 0x0a, 0x9e,
        0xee, 0xe6, 0x4b, 0x55, 0xd3, 0x9a, 0x21, 0x92, 0x99, 0x2a, 0x27, 0x4f, 0xc1,
        0xa8, 0x36, 0xba, 0x3c, 0x23, 0xa3, 0xfe, 0xeb, 0xbd, 0x45, 0x4d, 0x44, 0x23,
        0x64, 0x3c, 0xe8, 0x0e, 0x2a, 0x9a, 0xc9, 0x4f, 0xa5, 0x4c, 0xa4, 0x9f};

    uint8_t digest[64];
    syn_sha512(msg1, strlen(msg1), digest);
    TEST_ASSERT_EQUAL_MEMORY(exp1, digest, 64);

    /* Vector 2: Empty string "" */
    static const uint8_t exp_empty[64] = {
        0xcf, 0x83, 0xe1, 0x35, 0x7e, 0xef, 0xb8, 0xbd, 0xf1, 0x54, 0x28, 0x50, 0xd6,
        0x6d, 0x80, 0x07, 0xd6, 0x20, 0xe4, 0x05, 0x0b, 0x57, 0x15, 0xdc, 0x83, 0xf4,
        0xa9, 0x21, 0xd3, 0x6c, 0xe9, 0xce, 0x47, 0xd0, 0xd1, 0x3c, 0x5d, 0x85, 0xf2,
        0xb0, 0xff, 0x83, 0x18, 0xd2, 0x87, 0x7e, 0xec, 0x2f, 0x63, 0xb9, 0x31, 0xbd,
        0x47, 0x41, 0x7a, 0x81, 0xa5, 0x38, 0x32, 0x7a, 0xf9, 0x27, 0xda, 0x3e};
    syn_sha512("", 0, digest);
    TEST_ASSERT_EQUAL_MEMORY(exp_empty, digest, 64);

    /* Vector 3: 112-character message crossing 128-byte block boundary with streaming */
    static const char msg_long[] =
        "abcdefghbcdefghicdefghijdefghijkefghijklfghijklmghijklmnhijklmnoijklmnopjklmnopqklmnopqrl"
        "mnopqrsmnopqrstnopqrstu";
    static const uint8_t exp_long[64] = {
        0x8e, 0x95, 0x9b, 0x75, 0xda, 0xe3, 0x13, 0xda, 0x8c, 0xf4, 0xf7, 0x28, 0x14,
        0xfc, 0x14, 0x3f, 0x8f, 0x77, 0x79, 0xc6, 0xeb, 0x9f, 0x7f, 0xa1, 0x72, 0x99,
        0xae, 0xad, 0xb6, 0x88, 0x90, 0x18, 0x50, 0x1d, 0x28, 0x9e, 0x49, 0x00, 0xf7,
        0xe4, 0x33, 0x1b, 0x99, 0xde, 0xc4, 0xb5, 0x43, 0x3a, 0xc7, 0xd3, 0x29, 0xee,
        0xb6, 0xdd, 0x26, 0x54, 0x5e, 0x96, 0xe5, 0x5b, 0x87, 0x4b, 0xe9, 0x09};

    SYN_SHA512 ctx;
    syn_sha512_init(&ctx);
    /* Stream in chunks of 7 bytes */
    size_t total = strlen(msg_long);
    for (size_t offset = 0; offset < total; offset += 7) {
        size_t chunk = (total - offset > 7) ? 7 : (total - offset);
        syn_sha512_update(&ctx, msg_long + offset, chunk);
    }
    syn_sha512_final(&ctx, digest);
    TEST_ASSERT_EQUAL_MEMORY(exp_long, digest, 64);
}

